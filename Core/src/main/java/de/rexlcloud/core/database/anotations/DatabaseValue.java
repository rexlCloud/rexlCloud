package de.rexlcloud.core.database.anotations;
import lombok.NonNull;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.FIELD)
public @interface DatabaseValue {

    /**
     * Column name, the field name if empty. Letters, digits and '_'.
     */
    @NonNull String valueName() default "";

    /**
     * Maximum length of a String column: up to 255 a VARCHAR, above a TEXT/LONGTEXT.
     */
    int length() default 255;

    /**
     * Not enforced by the database; kept for compatibility.
     */
    boolean canBeNull() default false;

    /**
     * Primary key. int/long ids are generated by the database (AUTO_INCREMENT) and set on insert.
     */
    boolean id() default false;

    /**
     * Stores the value as JSON even if its type has its own column type. Types without one (lists, maps,
     * records, other objects) are always stored as JSON.
     */
    boolean serializeAsJson() default false;

}